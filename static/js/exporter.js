function app(){
    if(!window.annotatorApp) throw new Error("Annotator app is not ready.");
    return window.annotatorApp;
}
function stem(name){const i=name.lastIndexOf(".");return i>0?name.slice(0,i):name;}
function clamp01(v){return Math.max(0,Math.min(1,v));}
function downloadBlob(filename,blob){
    const url=URL.createObjectURL(blob),a=document.createElement("a");
    a.href=url;a.download=filename;document.body.appendChild(a);a.click();a.remove();
    setTimeout(()=>URL.revokeObjectURL(url),1500);
}
function downloadText(filename,text,type){downloadBlob(filename,new Blob([text],{type}));}
function setProgress(text){exportProgress.textContent=text;}
function getClasses(dataset){
    const names=app().getLabels().map(l=>l.name);
    const used=new Set(dataset.flatMap(item=>item.data.boxes.map(b=>b.label)));
    [...used].sort().forEach(n=>{if(!names.includes(n))names.push(n);});
    return names;
}
function getCorners(box){
    if(box.type==="four_point"&&Array.isArray(box.points)&&box.points.length===4)return app().deepClone(box.points);
    const [x1,y1,x2,y2]=box.bbox;return [[x1,y1],[x2,y1],[x2,y2],[x1,y2]];
}
async function ensureDataset(){
    await app().saveCurrent();
    const dataset=app().getDataset();
    if(!dataset.length){alert("No annotated images found.");return null;}
    return dataset;
}
async function makeZip(filename,zip){
    if(typeof JSZip==="undefined"){alert("ZIP support did not load. Check your internet connection and refresh.");return;}
    const blob=await zip.generateAsync({type:"blob",compression:"DEFLATE",compressionOptions:{level:6}},m=>setProgress(`Preparing ZIP: ${Math.round(m.percent)}%`));
    downloadBlob(filename,blob);setProgress("Export complete ✅");
}

exportMainBtn.addEventListener("click",async()=>{
    try{
        const dataset=await ensureDataset();if(!dataset)return;
        setProgress(`${dataset.length} annotated image(s) ready.`);exportDialogOverlay.hidden=false;
    }catch(e){console.error(e);alert(`Could not prepare export.\n\n${e.message||e}`);}
});
cancelExportBtn.addEventListener("click",()=>{exportDialogOverlay.hidden=true;setProgress("");});
document.addEventListener("keydown",e=>{if(e.key==="Escape"&&!exportDialogOverlay.hidden)exportDialogOverlay.hidden=true;},true);

// JSON
exportJsonBtn.addEventListener("click",async()=>{
    const dataset=await ensureDataset();if(!dataset)return;
    const pairs={};
    for(const {record,data} of dataset){pairs[record.name]={width:data.width,height:data.height,labels:[...new Set(data.boxes.map(b=>b.label))].sort(),boxes:app().deepClone(data.boxes)};}
    downloadText("annotations_pairs.json",JSON.stringify(pairs,null,2),"application/json;charset=utf-8");setProgress("JSON export complete ✅");
});

// CSV
function csvEscape(v){
    if(v===null||v===undefined)return "";const s=String(v);
    return /[",\r\n]/.test(s)?`"${s.replace(/"/g,'""')}"`:s;
}
exportCsvBtn.addEventListener("click",async()=>{
    const dataset=await ensureDataset();if(!dataset)return;
    const rows=[["filename","label","type","x1","y1","x2","y2","points","width","height"]];
    for(const {record,data} of dataset){for(const b of data.boxes){const [x1,y1,x2,y2]=b.bbox;const pts=b.points?JSON.stringify(b.points):"";rows.push([record.name,b.label,b.type||"two_point",x1,y1,x2,y2,pts,data.width,data.height]);}}
    downloadText("annotations.csv",rows.map(r=>r.map(csvEscape).join(",")).join("\n")+"\n","text/csv;charset=utf-8");setProgress("CSV export complete ✅");
});

// YOLO / YOLO-OBB
exportYoloBtn.addEventListener("click",()=>exportYolo(false));
exportYoloObbBtn.addEventListener("click",()=>exportYolo(true));
async function exportYolo(obb){
    const dataset=await ensureDataset();if(!dataset)return;
    if(typeof JSZip==="undefined"){alert("JSZip is unavailable.");return;}
    const classes=getClasses(dataset),zip=new JSZip(),imagesFolder=zip.folder("images"),labelsFolder=zip.folder(obb?"labels_obb":"labels");
    zip.file("classes.txt",classes.join("\n"));
    const yaml=["# YOLO dataset config (generated by Image Annotator)","path: .","train: images","val: images","","names:",...classes.map((n,i)=>`  ${i}: ${n}`)].join("\n")+"\n";
    zip.file("data.yaml",yaml);
    for(const {record,data} of dataset){
        imagesFolder.file(record.name,record.file);const W=data.width,H=data.height,lines=[];
        for(const b of data.boxes){const cid=classes.indexOf(b.label);if(cid<0)continue;
            if(obb){const coords=[];for(const [x,y] of getCorners(b)){coords.push(clamp01(x/W).toFixed(6),clamp01(y/H).toFixed(6));}lines.push(`${cid} ${coords.join(" ")}`);}
            else{const [x1,y1,x2,y2]=b.bbox;const xc=((x1+x2)/2)/W,yc=((y1+y2)/2)/H,w=(x2-x1)/W,h=(y2-y1)/H;lines.push(`${cid} ${xc.toFixed(6)} ${yc.toFixed(6)} ${w.toFixed(6)} ${h.toFixed(6)}`);}
        }
        labelsFolder.file(`${stem(record.name)}.txt`,lines.join("\n")+(lines.length?"\n":""));
    }
    await makeZip(obb?"yolo_obb_dataset.zip":"yolo_dataset.zip",zip);
}

// Pascal VOC
function xmlEscape(v){return String(v).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;").replace(/'/g,"&apos;");}
function vocXml(filename,data){
    const L=['<?xml version="1.0" ?>','<annotation>','  <folder>JPEGImages</folder>',`  <filename>${xmlEscape(filename)}</filename>`,'  <size>',`    <width>${data.width}</width>`,`    <height>${data.height}</height>`,'    <depth>3</depth>','  </size>','  <segmented>0</segmented>'];
    for(const b of data.boxes){const [x1,y1,x2,y2]=b.bbox;L.push('  <object>',`    <name>${xmlEscape(b.label)}</name>`,'    <pose>Unspecified</pose>','    <truncated>0</truncated>','    <difficult>0</difficult>','    <bndbox>',`      <xmin>${Math.trunc(x1)}</xmin>`,`      <ymin>${Math.trunc(y1)}</ymin>`,`      <xmax>${Math.trunc(x2)}</xmax>`,`      <ymax>${Math.trunc(y2)}</ymax>`,'    </bndbox>','  </object>');}
    L.push('</annotation>');return L.join("\n")+"\n";
}
exportVocBtn.addEventListener("click",async()=>{
    const dataset=await ensureDataset();if(!dataset)return;if(typeof JSZip==="undefined"){alert("JSZip is unavailable.");return;}
    const zip=new JSZip(),imgs=zip.folder("JPEGImages"),anns=zip.folder("Annotations");
    for(const {record,data} of dataset){imgs.file(record.name,record.file);anns.file(`${stem(record.name)}.xml`,vocXml(record.name,data));}
    await makeZip("pascal_voc_dataset.zip",zip);
});

// COCO
exportCocoBtn.addEventListener("click",async()=>{
    const dataset=await ensureDataset();if(!dataset)return;if(typeof JSZip==="undefined"){alert("JSZip is unavailable.");return;}
    const zip=new JSZip(),imgs=zip.folder("images"),classes=getClasses(dataset),labelToCat=Object.fromEntries(classes.map((n,i)=>[n,i+1]));
    const coco={info:{description:"Exported from desktop_annotator.py-compatible web app"},licenses:[],images:[],annotations:[],categories:classes.map((n,i)=>({id:i+1,name:n,supercategory:"object"}))};
    let annId=1;
    dataset.forEach(({record,data},idx)=>{
        const imageId=idx+1;imgs.file(record.name,record.file);coco.images.push({id:imageId,file_name:record.name,width:data.width,height:data.height});
        for(const b of data.boxes){const [x1,y1,x2,y2]=b.bbox,w=x2-x1,h=y2-y1;const entry={id:annId++,image_id:imageId,category_id:labelToCat[b.label],bbox:[x1,y1,w,h],area:w*h,iscrowd:0,segmentation:(b.type==="four_point"&&Array.isArray(b.points))?[b.points.flat()]:[]};coco.annotations.push(entry);}
    });
    zip.file("annotations.json",JSON.stringify(coco,null,2));await makeZip("coco_dataset.zip",zip);
});
